"""Data from the server: prices and other tables the addons read, kept up to date by the app.

Every 5 minutes per game, while signed in and while the "Data from the server" setting is on, the app
asks the XPCompass server for its list of data files (GET /data). The list is trusted only through its
signature: an Ed25519 key built into the app (DATA_KEYS) must have signed the exact bytes, the list
must name this install, and its version must be newer than the last one taken. Each file the list
names whose checksum changed is fetched (GET /data/<name>), checked against the list, read as JSON
and turned into Lua by this module. Server text never becomes code: the app writes every value itself,
as a number, a quoted and escaped string, a boolean or a table, and refuses anything else.

The result goes into one addon folder per game client, XPCompass_Data, which holds exactly two files
the app writes: the .toc that client loads and Data.lua. Each is written to a temporary file in the
same folder, flushed, read back and then swapped in, so a failure leaves the previous copy. The last
good copy of each file is kept beside uploads.json (data-files/<game>/<name>.json) with the state
(data.json), so a missing or damaged Data.lua is written again from them. Nothing is written when
nothing changed, except the time in meta.written, at most once an hour while the app is in touch with
the server (the addons take a recent time to mean the app is running).

Turning the setting off stops asking and writes Data.lua with no files, so every feature falls back to
its defaults. After a failure the next try waits 30 minutes; a server with no key yet (503) is the
same as nothing new.
"""
