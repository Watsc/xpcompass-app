class Channel:
    def __init__(self, settings, uploader, keys=None, get=None, clock=time.time, replace=os.replace, path=None):
        self.settings, self.uploader = settings, uploader
        self.keys = DATA_KEYS if keys is None else keys
        self.get = get or self._get
        self.clock, self.replace = clock, replace
        beside = getattr(uploader, "path", None)            # uploads.json, in the app's data folder
        self.path = path or (Path(beside).with_name("data.json") if beside else system.data_dir() / "data.json")
        self.store = self.path.with_name("data-files")
        self.state = self._load()
        self.last = None            # what happened last, for anyone who asks

    # The app's record

    def _load(self):
        try:
            state = json.loads(self.path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            state = {}
        state = state if isinstance(state, dict) else {}
        state["games"] = state.get("games") if isinstance(state.get("games"), dict) else {}
        return state

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        temp = self.path.with_name(self.path.name + ".tmp")
        temp.write_text(json.dumps(self.state, indent=1), encoding="utf-8")
        os.replace(temp, self.path)

    def game(self, game_id):
        mine = self.state["games"].setdefault(game_id, {})
        for key, default in (("version", 0), ("revision", 0), ("etag", None), ("asked_with", None),
                             ("files", {}), ("next", 0), ("written", 0), ("wrote", None)):
            mine.setdefault(key, default)
        return mine

    def bind_scope(self, game_id):
        """A refreshed token, account change or entitlement change cannot reuse private cached bytes."""
        account = getattr(self.uploader, "account", None)
        session = account.session() if account else None
        scope = hashlib.sha256(json.dumps([self.settings.server, self.uploader.install, game_id,
            (session or {}).get("account_id") or (session or {}).get("token"), (session or {}).get("roles"),
            (session or {}).get("prerelease")], sort_keys=True).encode()).hexdigest() if session else None
        mine = self.game(game_id)
        if mine.get("scope") != scope or (not session and mine["files"]):
            self.clear(game_id)
            self.game(game_id)["scope"] = scope

    def clear(self, game_id):
        mine = self.game(game_id)
        for name in list(mine["files"]):
            try:
                self.good_path(game_id, name).unlink(missing_ok=True)
            except (OSError, DataError):
                pass
        mine.update(files={}, version=0, revision=0, etag=None, asked_with=None, next=0, wrote=None)

    def enabled(self):
        return getattr(self.settings, "data_channel", True) is not False

    def signed_in(self):
        account = getattr(self.uploader, "account", None)
        return bool(account and account.session())

    def good_path(self, game_id, name):
        if game_id not in TOCS or not NAME.fullmatch(name):
            raise DataError("not a data file name")
        return self.store / game_id / f"{name}.json"

    def good(self, game_id, name, sha):
        """The last good copy's bytes, when they still match `sha`."""
        try:
            data = self.good_path(game_id, name).read_bytes()
        except (OSError, DataError):
            return None
        return data if hashlib.sha256(data).hexdigest() == sha else None

    # Each minute (tray.py)

    def tick(self, clients):
        """Look after each game's data once: ask the server when it is time, then make Data.lua match."""
        on = self.enabled()
        for game_id, folder in clients.items():
            addons = Path(folder) / "Interface" / "AddOns"
            if game_id not in TOCS or not (addons / games.ADDONS[0]).is_dir():
                continue                    # no XPCompass in that client: nothing to feed
            self.bind_scope(game_id)
            mine = self.game(game_id)
            in_touch = False
            if on and self.signed_in() and self.clock() >= mine["next"]:
                in_touch = self.poll(game_id, folder)
            try:
                self.sync(game_id, folder, on and self.signed_in(), in_touch)
            except (OSError, DataError) as error:
                self.last = f"Could not write the data for {game_id}: {error}"
        self.save()

    def poll(self, game_id, folder):
        """Ask the server once. True when it answered with a list taken or nothing new."""
        mine, now = self.game(game_id), self.clock()
        mine["next"] = now + EVERY
        houses = ",".join(houses_in(folder))
        params = {"game": game_id, **({"houses": houses} if houses else {})}
        etag = mine["etag"] if mine["version"] and mine["asked_with"] == houses else None
        try:
            status, headers, body = self.get("/data", params, etag, MAX_LIST)
            if status == 304:
                return True
            if status == 503:
                return False
            if status in (401, 403):
                self.clear(game_id)
                raise DataError("access to cached data was withdrawn")
            if status != 200:
                raise DataError(f"the server answered {status}")
            listing = verify_list(body, headers.get("x-xpc-signature"), self.keys, self.uploader.install,
                                  mine["version"])
        except (DataError, uploads.UploadError) as error:
            mine["next"] = now + BACKOFF
            self.last = f"Data not updated, will try again: {error}"
            return False
        self.take(game_id, listing, params)
        tag = headers.get("etag")
        mine["etag"] = tag if isinstance(tag, str) and ETAG.fullmatch(tag) else None
        mine["asked_with"] = houses
        return True

    def take(self, game_id, listing, params):
        """Fetch what changed in an accepted list; a file that fails keeps its last good copy."""
        mine, kept = self.game(game_id), {}
        for entry in listing["files"]:
            name, sha = entry["name"], entry["sha256"]
            before = mine["files"].get(name)
            if before and before.get("sha") == sha and self.good(game_id, name, sha) is not None:
                kept[name] = {"sha": sha, "revision": entry["revision"]}
                continue
            status = None
            try:
                status, _, data = self.get("/data/" + urllib.parse.quote(name), params, None, entry["size"] + 1)
                if status != 200:
                    raise DataError(f"{name}: the server answered {status}")
                check_file(data, entry)
                path = self.good_path(game_id, name)
                path.parent.mkdir(parents=True, exist_ok=True)
                temp = path.with_name(path.name + ".tmp")
                temp.write_bytes(data)
                os.replace(temp, path)
                kept[name] = {"sha": sha, "revision": entry["revision"]}
            except (DataError, OSError, uploads.UploadError) as error:
                self.last = f"Data file not taken: {error}"
                if status not in (401, 403, 404) and before and self.good(game_id, name, before.get("sha")) is not None:
                    kept[name] = before
        for name in set(mine["files"]) - set(kept):     # gone from the list: dropped
            try:
                self.good_path(game_id, name).unlink()
            except (OSError, DataError):
                pass
        mine.update(files=kept, version=listing["version"], revision=listing["revision"])

    def sync(self, game_id, folder, on, in_touch=False):
        """Make the client's Data.lua match: the files' last good copies, or none while the setting is off.
        Written only when something changed, it is missing or not as written, or (in touch with the
        server) its time is an hour old."""
        mine = self.game(game_id)
        addons = Path(folder) / "Interface" / "AddOns"
        out, toc, data = output_paths(addons, game_id)
        if not data.exists() and (not on or not mine["version"]):
            return                          # nothing taken yet, or off with nothing to empty
        channel = self.channel(folder, game_id)
        files = {name: info["sha"] for name, info in sorted(mine["files"].items())} if on else {}
        meta = {"format": 1, "version": mine["version"], "revision": mine["revision"]}
        intent = json.dumps([str(data), meta, channel, files])
        try:
            stat = data.stat()
            seen = [stat.st_mtime_ns, stat.st_size]
        except OSError:
            seen = None
        wrote = mine["wrote"] or {}
        stale = in_touch and self.clock() - mine["written"] >= REFRESH
        if wrote.get("intent") == intent and wrote.get("seen") == seen and not stale:
            return
        sources = {}
        for name, sha in files.items():
            good = self.good(game_id, name, sha)
            if good is None:
                continue
            try:
                sources[name] = to_lua(parse_json(good))
            except DataError:
                continue
        written = int(self.clock())
        text = render(dict(meta, written=written, **({"channel": channel} if channel else {})), sources)
        out.mkdir(exist_ok=True)
        output_paths(addons, game_id)           # again, now that the folder is there
        want_toc = toc_text(game_id)
        try:
            current = toc.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            current = None
        if current != want_toc:
            write_atomic(toc, want_toc, self.replace)
        write_atomic(data, text, self.replace)
        stat = data.stat()
        mine["written"] = written
        mine["wrote"] = {"intent": intent, "seen": [stat.st_mtime_ns, stat.st_size]}

    @staticmethod
    def channel(folder, game_id):
        """The channel of the XPCompass build the app installed in that client, or None."""
        try:
            manifest = install.installed(folder, games.GAMES[game_id].package) or {}
        except (OSError, ValueError, KeyError):
            return None
        channel = manifest.get("channel")
        return channels.WIRE[channels.canonical(channel)] if channel in CHANNELS else None

    # Talking to the server

    def _token(self):
        return self.uploader.signed_token()

    def _get(self, path, params, etag, limit):
        """(status, {lower-case header: value}, body) for a GET, the body cut at `limit` bytes. Retries
        once with a fresh token after a 401."""
        token = self._token()
        status, headers, body = self._request(path, params, etag, limit, token)
        account = getattr(self.uploader, "account", None)
        if status == 401 and token and account:
            try:
                token = account.refresh()["token"]
            except auth.AuthError as error:
                raise DataError(auth.SIGN_IN_FIRST) from error
            status, headers, body = self._request(path, params, etag, limit, token)
        return status, headers, body

    def _request(self, path, params, etag, limit, token):
        url = self.settings.server.rstrip("/") + path + "?" + urllib.parse.urlencode(params)
        headers = {"X-XPC-Install": self.uploader.install, "User-Agent": "ForeverCoachCompanion"}
        if token:
            headers["Authorization"] = f"Bearer {token}"
        if etag:
            headers["If-None-Match"] = etag
        request = urllib.request.Request(url, method="GET", headers=headers)
        try:
            with tls.urlopen(request, timeout=30) as response:
                return response.status, {k.lower(): v for k, v in response.headers.items()}, response.read(limit + 1)
        except urllib.error.HTTPError as error:
            return error.code, {k.lower(): v for k, v in (error.headers or {}).items()}, error.read(limit + 1)
        except OSError as error:
            raise DataError(f"could not reach the XPCompass server: {error}") from error

