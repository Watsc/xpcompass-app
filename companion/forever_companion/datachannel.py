class DataError(Exception):
    """A list or file that is not taken; the message says why."""


def _int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def _no_constants(name):
    raise DataError(f"{name} is not a number this app takes")


def parse_json(data):
    """JSON from bytes, with NaN and Infinity refused."""
    try:
        return json.loads(data.decode("utf-8"), parse_constant=_no_constants)
    except DataError:
        raise
    except (UnicodeDecodeError, ValueError, RecursionError) as error:
        raise DataError(f"not JSON: {error}") from error


# ---------------------------------------------------------------------------------------------
# The signed list
# ---------------------------------------------------------------------------------------------

def signed_by(body, signature, keys):
    """Whether one of `keys` signed `body`."""
    try:
        sig = base64.b64decode(signature or "", validate=True)
    except ValueError:
        return False
    for key in keys:
        try:
            Ed25519PublicKey.from_public_bytes(base64.b64decode(key, validate=True)).verify(sig, body)
            return True
        except Exception:   # noqa: BLE001 - a bad key or a bad signature both mean "not this key"
            continue
    return False


def verify_list(body, signature, keys, install_id, last_version):
    """The list as a dict, or DataError: signed, for this install, newer, and within the limits."""
    if len(body) > MAX_LIST:
        raise DataError("the list is too large")
    if not signed_by(body, signature, keys):
        raise DataError("the list's signature does not check out")
    listing = parse_json(body)
    if not isinstance(listing, dict) or not _int(listing.get("format")) or listing["format"] != 1:
        raise DataError("the list is not in a format this app reads")
    if listing.get("for") != install_id:
        raise DataError("the list was made for another install")
    version = listing.get("version")
    if not _int(version) or version <= last_version:
        raise DataError("the list is not newer than the last one taken")
    if not _int(listing.get("revision")) or not _int(listing.get("time")):
        raise DataError("the list has no revision or time")
    files = listing.get("files")
    if not isinstance(files, list) or len(files) > MAX_FILES:
        raise DataError("the list names too many files")
    names, total = set(), 0
    for entry in files:
        if not isinstance(entry, dict):
            raise DataError("a file entry is not an object")
        name, sha, size = entry.get("name"), entry.get("sha256"), entry.get("size")
        if not isinstance(name, str) or not NAME.fullmatch(name) or name in names:
            raise DataError("a file name is not allowed")
        if not isinstance(sha, str) or not SHA.fullmatch(sha):
            raise DataError(f"{name}: the checksum is not 64 hex digits")
        if not _int(size) or not 0 <= size <= MAX_FILE:
            raise DataError(f"{name}: the size is out of range")
        if not _int(entry.get("revision")):
            raise DataError(f"{name}: no revision")
        names.add(name)
        total += size
    if total > MAX_TOTAL:
        raise DataError("the files are too large together")
    return listing


# ---------------------------------------------------------------------------------------------
# JSON to Lua, written by the app: numbers, escaped strings, booleans and tables only
# ---------------------------------------------------------------------------------------------

def lua_string(text, limit=MAX_STRING):
    """A Lua string literal: printable ASCII as itself, every other byte (and " and \\) as \\ddd."""
    try:
        raw = text.encode("utf-8")
    except UnicodeEncodeError as error:
        raise DataError("a string is not valid text") from error
    if len(raw) > limit:
        raise DataError("a string is too long")
    return '"' + "".join(chr(b) if 0x20 <= b <= 0x7E and b not in (0x22, 0x5C) else f"\\{b:03d}"
                         for b in raw) + '"'


def to_lua(value):
    """Lua source for one JSON value, or DataError when it breaks a rule or a limit."""
    count = [0]

    def write(item, depth):
        count[0] += 1
        if count[0] > MAX_VALUES:
            raise DataError("too many values")
        if item is True or item is False:
            return "true" if item else "false"
        if _int(item):
            if abs(item) > MAX_NUMBER:
                raise DataError("a number is too large")
            return str(item)
        if isinstance(item, float):
            if not math.isfinite(item) or abs(item) > MAX_NUMBER:
                raise DataError("a number is not finite or too large")
            return repr(item)
        if isinstance(item, str):
            return lua_string(item)
        if isinstance(item, (list, dict)):
            if depth >= MAX_DEPTH:
                raise DataError("the tables are nested too deep")
            if isinstance(item, list):
                parts = [f"[{index}]={write(entry, depth + 1)}" for index, entry in enumerate(item, 1)]
            else:
                parts = []
                for key, entry in item.items():
                    if not isinstance(key, str):
                        raise DataError("a table key is not a string")
                    # A key is a constant too: Lua 5.1 holds at most 262,143 in one function, and a
                    # file over that would stop the whole of Data.lua loading.
                    count[0] += 1
                    parts.append(f"[{lua_string(key, MAX_KEY)}]={write(entry, depth + 1)}")
            return "{" + ",".join(parts) + "}"
        raise DataError("a value is not a number, string, boolean or table")

    return write(value, 0)


def check_file(data, entry):
    """The file's Lua source when its bytes match the list's entry and convert; else DataError."""
    if len(data) != entry["size"]:
        raise DataError(f"{entry['name']}: the size does not match the list")
    if hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise DataError(f"{entry['name']}: the checksum does not match the list")
    return to_lua(parse_json(data))


def meta_lua(meta):
    order = ("format", "version", "revision", "written", "channel")
    parts = []
    for key in order:
        if key in meta:
            value = meta[key]
            parts.append(f"{key} = {lua_string(value) if isinstance(value, str) else int(value)}")
    return "{ " + ", ".join(parts) + " }"


def render(meta, files):
    """Data.lua's text: `files` is {name: Lua source}, written in name order."""
    lines = [HEADER, f"ForeverCoachData = {{ meta = {meta_lua(meta)}, files = {{}} }}\n"]
    for name in sorted(files):
        lines.append(f"ForeverCoachData.files[{lua_string(name)}] = (function() return {files[name]} end)()\n")
    return "".join(lines)


def toc_text(game_id):
    return "\n".join((f"## Interface: {TOCS[game_id][1]}", *TOC_LINES)) + "\n"


