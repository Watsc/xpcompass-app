def output_paths(addons, game_id):
    """(folder, toc, Data.lua) inside a client's AddOns folder, from fixed names only. DataError when
    any of them would resolve outside it (a link in the way)."""
    base = Path(os.path.realpath(addons))
    folder = base / FOLDER
    paths = (folder, folder / f"{FOLDER}{TOCS[game_id][0]}.toc", folder / DATA_FILE)
    for path in paths:
        real = Path(os.path.realpath(path))
        if base not in real.parents or (path != folder and real.parent != Path(os.path.realpath(folder))):
            raise DataError(f"{path} is not inside the AddOns folder")
    return paths


def write_atomic(path, text, replace=os.replace):
    """Write `text` to `path` through a temporary file in the same folder: flushed, read back and
    compared, then swapped in. On any failure the old file stays and the temporary file is removed."""
    data = text.encode("utf-8")
    temp = path.with_name("." + path.name + ".xpc-tmp")
    try:
        with open(temp, "wb") as out:
            out.write(data)
            out.flush()
            os.fsync(out.fileno())
        if temp.read_bytes() != data:
            raise OSError("the written file did not read back the same")
        replace(temp, path)
    except BaseException:
        try:
            temp.unlink()
        except OSError:
            pass
        raise


def houses_in(game):
    """The auction houses ("Realm-Horde") of this client's characters, newest scans first, from XPC -
    Market's saved files; at most MAX_HOUSES, sorted."""
    found = []
    accounts = Path(game) / "WTF" / "Account"
    if not accounts.is_dir():
        return []
    for path in sorted(accounts.glob("*/SavedVariables/XPCompass_Market.lua")):
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for house in reversed(HOUSE_IN_FILE.findall(text)):      # scans are appended: newest last
            if HOUSE.fullmatch(house) and house not in found:
                found.append(house)
    return sorted(found[:MAX_HOUSES])


